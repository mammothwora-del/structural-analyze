_SQ2 = math.sqrt(2.0)


def _g(v):
    return f"{v:g}"


def _entries():
    out = []
    mm, cm2, cm3, cm4 = 1e-3, 1e-4, 1e-6, 1e-8
    for H_, B, tw, tf, r, A, W, Ix, Iy, Zx, Zy in H:
        out.append(dict(family="H", name=f"H {_g(H_)}x{_g(B)}x{_g(tw)}x{_g(tf)}", shape="I", fab="rolled",
                        dims=dict(h=H_ * mm, bf=B * mm, tw=tw * mm, tf=tf * mm),
                        A=A * cm2, Iy=Ix * cm4, Iz=Iy * cm4, Sy=Zx * cm3, Sz=Zy * cm3))
    for H_, B, tw, tf, r1, r2, A, W, Ix, Iy, Zx, Zy in I:
        out.append(dict(family="I", name=f"I {_g(H_)}x{_g(B)}x{_g(tw)}x{_g(tf)}", shape="I", fab="rolled",
                        dims=dict(h=H_ * mm, bf=B * mm, tw=tw * mm, tf=tf * mm),
                        A=A * cm2, Iy=Ix * cm4, Iz=Iy * cm4, Sy=Zx * cm3, Sz=Zy * cm3))
    for H_, B, tw, tf, r1, r2, A, W, Cy, Ix, Iy, Zx, Zy in C:
        out.append(dict(family="C", name=f"C {_g(H_)}x{_g(B)}x{_g(tw)}x{_g(tf)}", shape="channel", fab="rolled",
                        dims=dict(h=H_ * mm, b=B * mm, tw=tw * mm, tf=tf * mm),
                        A=A * cm2, Iy=Ix * cm4, Iz=Iy * cm4, Sy=Zx * cm3, Sz=Zy * cm3, xc=Cy * 1e-2))
    for b, t, r1, r2, A, W, c, Ix, Iu, Iv, Zx in L:
        b_, t_, c_ = b * mm, t * mm, c * 1e-2
        out.append(dict(family="L", name=f"L {_g(b)}x{_g(b)}x{_g(t)}", shape="angle", fab="rolled",
                        dims=dict(b=b_, t=t_), A=A * cm2, Iy=Iu * cm4, Iz=Iv * cm4,
                        Sy=Iu * cm4 / (b_ / _SQ2), Sz=Iv * cm4 / max(_SQ2 * c_, (b_ + t_) / _SQ2 - _SQ2 * c_), xc=c_))
    for H_, B, Cl, t, A, W, Cy, Ix, Iy, Zx, Zy, xs in LC:
        out.append(dict(family="LC", name=f"LC {_g(H_)}x{_g(B)}x{_g(Cl)}x{_g(t)}", shape="lipchannel", fab="cold",
                        dims=dict(h=H_ * mm, b=B * mm, c=Cl * mm, t=t * mm),
                        A=A * cm2, Iy=Ix * cm4, Iz=Iy * cm4, Sy=Zx * cm3, Sz=Zy * cm3, xc=Cy * 1e-2, xs=xs * 1e-2))
    for a, t, W, A, I_, Z in SHS:
        out.append(dict(family="SHS", name=f"SHS {_g(a)}x{_g(a)}x{_g(t)}", shape="box", fab="cold",
                        dims=dict(h=a * mm, b=a * mm, t=t * mm), A=A * cm2, Iy=I_ * cm4, Iz=I_ * cm4, Sy=Z * cm3, Sz=Z * cm3))
    for H_, B, t, W, A, Ix, Iy, Zx, Zy in RHS:
        out.append(dict(family="RHS", name=f"RHS {_g(H_)}x{_g(B)}x{_g(t)}", shape="box", fab="cold",
                        dims=dict(h=H_ * mm, b=B * mm, t=t * mm), A=A * cm2, Iy=Ix * cm4, Iz=Iy * cm4, Sy=Zx * cm3, Sz=Zy * cm3))
    for D, t, W, A, I_, Z in CHS:
        out.append(dict(family="CHS", name=f"CHS {_g(D)}x{_g(t)}", shape="pipe", fab="cold",
                        dims=dict(d=D * mm, t=t * mm), A=A * cm2, Iy=I_ * cm4, Iz=I_ * cm4, Sy=Z * cm3, Sz=Z * cm3))
    for e in out:
        e["mass"] = e["A"] * 7850.0       # kg/m from the table area
    return out


TABLE = {e["name"]: e for e in _entries()}


def table_props(sec: dict) -> dict | None:
    """The supplier's properties for a section picked from the tables, if its dimensions are still the table's."""
    e = TABLE.get(sec.get("catalog") or "")
    if not e or e["shape"] != sec.get("shape"):
        return None
    try:
        if any(abs(float(sec[k]) - v) > 1e-9 for k, v in e["dims"].items()):
            return None
    except (KeyError, TypeError, ValueError):
        return None
    return e
